#!/usr/bin/env node
/**
 * Dev tool: bundles exercise images from free-exercise-db (Unlicense / public domain).
 *
 *   node scripts/exercise-images/build.mjs            download, convert, generate
 *   node scripts/exercise-images/build.mjs --report   only print the mapping report
 *
 * mapping.json (our exercise key → dataset id) is the hand-reviewed source of truth.
 * Output: assets/exercises/<key>/{0,1}.webp and src/constants/exerciseImages.ts.
 * Not imported by the app; it never runs at app start.
 */
import { Buffer } from 'node:buffer';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import prettier from 'prettier';
import sharp from 'sharp';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const DATASET_URL =
  'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json';
const IMAGE_BASE = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises/';
const ASSET_DIR = path.join(ROOT, 'assets/exercises');
const OUTPUT_TS = path.join(ROOT, 'src/constants/exerciseImages.ts');
const MAX_WIDTH = 600;
const TARGET_BYTES = 60 * 1024;
const QUALITIES = [72, 64, 56, 48, 40];
const CONCURRENCY = 6;

const reportOnly = process.argv.includes('--report');

async function fetchWithRetry(url, as = 'buffer', attempts = 3) {
  for (let i = 1; ; i++) {
    try {
      const res = await fetch(url, { signal: AbortSignal.timeout(30_000) });
      if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
      return as === 'json' ? await res.json() : Buffer.from(await res.arrayBuffer());
    } catch (error) {
      if (i >= attempts) throw error;
      await new Promise((r) => setTimeout(r, 1000 * i));
    }
  }
}

/** Resized WebP under the size target (lowering quality step by step). */
async function toWebp(input) {
  let output;
  for (const quality of QUALITIES) {
    output = await sharp(input)
      .resize({ width: MAX_WIDTH, withoutEnlargement: true })
      .webp({ quality, effort: 6 })
      .toBuffer();
    if (output.length <= TARGET_BYTES) break;
  }
  return output;
}

async function mapLimit(items, limit, fn) {
  const results = new Array(items.length);
  let next = 0;
  const workers = Array.from({ length: limit }, async () => {
    while (next < items.length) {
      const index = next++;
      results[index] = await fn(items[index], index);
    }
  });
  await Promise.all(workers);
  return results;
}

function generateTs(keys) {
  const lines = keys.map(
    (key) =>
      `  '${key}': [require('../../assets/exercises/${key}/0.webp'), require('../../assets/exercises/${key}/1.webp')],`,
  );
  return `// Generated by scripts/exercise-images/build.mjs — do not edit by hand.
// Images: free-exercise-db (https://github.com/yuhonas/free-exercise-db), public domain (Unlicense).
// Metro needs static require() calls to bundle the assets.

/** Start and end position images for built-in exercises, by exercise key. */
export const EXERCISE_IMAGES: Readonly<Record<string, readonly [number, number]>> = {
${lines.join('\n')}
};
`;
}

const mapping = JSON.parse(
  await fs.readFile(
    path.join(path.dirname(fileURLToPath(import.meta.url)), 'mapping.json'),
    'utf8',
  ),
);
console.log('Downloading dataset…');
const dataset = await fetchWithRetry(DATASET_URL, 'json');
const byId = new Map(dataset.map((entry) => [entry.id, entry]));

const matched = [];
const unmatched = [];
const review = [];
const problems = [];
for (const [key, entry] of Object.entries(mapping)) {
  if (!entry.datasetId) {
    unmatched.push({ key, note: entry.note ?? '' });
    continue;
  }
  const item = byId.get(entry.datasetId);
  if (!item || (item.images ?? []).length < 2) {
    problems.push(`${key}: dataset id "${entry.datasetId}" not found or has fewer than 2 images`);
    continue;
  }
  matched.push({ key, item, startIndex: entry.startIndex === 1 ? 1 : 0 });
  if (entry.confidence !== 'high')
    review.push({ key, id: entry.datasetId, confidence: entry.confidence, note: entry.note ?? '' });
}

console.log(
  `\nMatched: ${matched.length}   Unmatched: ${unmatched.length}   Needs review (medium/low): ${review.length}`,
);
if (unmatched.length) {
  console.log('\nUnmatched (no image, the muscle icon is shown):');
  for (const u of unmatched) console.log(`  - ${u.key}: ${u.note}`);
}
if (review.length) {
  console.log('\nLower-confidence matches:');
  for (const r of review) console.log(`  - [${r.confidence}] ${r.key} → ${r.id}: ${r.note}`);
}
if (problems.length) {
  console.error('\nProblems:\n  ' + problems.join('\n  '));
  process.exit(1);
}
if (reportOnly) process.exit(0);

await fs.mkdir(ASSET_DIR, { recursive: true });
const sizes = await mapLimit(matched, CONCURRENCY, async ({ key, item, startIndex }) => {
  const dir = path.join(ASSET_DIR, key);
  await fs.mkdir(dir, { recursive: true });
  const out = [];
  // `startIndex: 1` in mapping.json swaps the frames when the dataset's first one is only a setup.
  const frames = startIndex === 1 ? [item.images[1], item.images[0]] : item.images.slice(0, 2);
  for (const [index, imagePath] of frames.entries()) {
    const webp = await toWebp(await fetchWithRetry(IMAGE_BASE + imagePath));
    await fs.writeFile(path.join(dir, `${index}.webp`), webp);
    out.push(webp.length);
  }
  process.stdout.write('.');
  return out;
});

// Remove folders for exercises that are no longer mapped.
const keep = new Set(matched.map((m) => m.key));
for (const dir of await fs.readdir(ASSET_DIR)) {
  if (!keep.has(dir)) await fs.rm(path.join(ASSET_DIR, dir), { recursive: true, force: true });
}

const prettierConfig = await prettier.resolveConfig(OUTPUT_TS);
await fs.writeFile(
  OUTPUT_TS,
  await prettier.format(generateTs([...keep].sort()), { ...prettierConfig, filepath: OUTPUT_TS }),
);
const all = sizes.flat();
const total = all.reduce((a, b) => a + b, 0);
console.log(
  `\n\nWrote ${all.length} images (${(total / 1024 / 1024).toFixed(2)} MB total, ` +
    `max ${(Math.max(...all) / 1024).toFixed(1)} KB, avg ${(total / all.length / 1024).toFixed(1)} KB).`,
);
console.log(`Generated ${path.relative(ROOT, OUTPUT_TS)}`);
